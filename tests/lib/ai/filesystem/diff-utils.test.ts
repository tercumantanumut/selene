import { describe, expect, it } from "vitest";
import {
  calculateChangedLineCount,
  generateBeforeAfterDiff,
  generateLineNumberDiff,
} from "@/lib/ai/filesystem/diff-utils";

function highlightedLines(diff: string, marker: "+" | "-"): string[] {
  return diff
    .split("\n")
    .filter((line) => new RegExp(`\\| \\${marker} `).test(line));
}

describe("diff-utils", () => {
  it("counts the changed hunk lines generated by generateBeforeAfterDiff", () => {
    const before = `line1
line2
line3
line4
line5
line6
line7`;
    const after = `line1
line2
LINE3
line4
line5
line6
line7`;

    const diff = generateBeforeAfterDiff("example.txt", before, after);

    expect(calculateChangedLineCount(before, after)).toBe(1);
    expect(diff).toContain("3 | - line3");
    expect(diff).toContain("3 | + LINE3");
    expect(highlightedLines(diff, "-")).toHaveLength(1);
    expect(highlightedLines(diff, "+")).toHaveLength(1);
  });

  it("separates non-adjacent changes instead of marking the lines between them as changed", () => {
    const before = Array.from({ length: 12 }, (_, index) => `line${index + 1}`).join("\n");
    const afterLines = before.split("\n");
    afterLines[1] = "LINE2";
    afterLines[9] = "LINE10";
    const after = afterLines.join("\n");

    const diff = generateBeforeAfterDiff("example.txt", before, after);

    expect(calculateChangedLineCount(before, after)).toBe(2);
    expect(highlightedLines(diff, "-")).toEqual([
      "2 | - line2",
      "10 | - line10",
    ]);
    expect(highlightedLines(diff, "+")).toEqual([
      "2 | + LINE2",
      "10 | + LINE10",
    ]);
    expect(diff).toContain("1 1 |   line1");
    expect(diff).not.toContain("5 | - line5");
    expect(diff).not.toContain("5 | + line5");
  });

  it("keeps unchanged lines inside a replacement snippet as neutral context", () => {
    const original = `header
line1
line2
line3
line4
line5
footer`;
    const oldString = `line1
line2
line3
line4
line5`;
    const newString = `line1
LINE2
line3
LINE4
line5`;

    const diff = generateLineNumberDiff(
      "example.txt",
      original,
      oldString,
      newString
    );

    expect(highlightedLines(diff, "-")).toEqual([
      "3 | - line2",
      "5 | - line4",
    ]);
    expect(highlightedLines(diff, "+")).toEqual([
      "3 | + LINE2",
      "5 | + LINE4",
    ]);
    expect(diff).toContain("2 2 |   line1");
    expect(diff).toContain("4 4 |   line3");
    expect(diff).not.toContain("2 | - line1");
    expect(diff).not.toContain("2 | + line1");
  });

  it("counts insertions and deletions by the larger side of each change group", () => {
    const before = `line1
line2
line4`;
    const after = `line1
line2
line3
line3b
line4`;

    expect(calculateChangedLineCount(before, after)).toBe(2);
  });

  it("does not double-count a modified final line without a trailing newline", () => {
    expect(calculateChangedLineCount("old", "new")).toBe(1);
  });

  it("returns zero for identical content", () => {
    const content = `line1
line2`;

    expect(calculateChangedLineCount(content, content)).toBe(0);
    expect(generateBeforeAfterDiff("example.txt", content, content)).toBe("");
  });
});
